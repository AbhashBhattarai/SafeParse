# generate_headers.py — Generate all C parser headers from spec files.
#
# WHAT: Reads each .spec file in specs/ and runs compile_spec() in both
#       "naive" and "optimized" modes, writing the result to .h files
#       in c_tests/generated/.
#
# WHY:  The C test harnesses (run_cases.c, fuzz_*.c, bench.c) #include
#       these generated headers.  This script ties the Python compiler
#       to the C evaluation code.
#
# USAGE (from project root):
#   python c_tests/generate_headers.py

import os
import sys

# Add the project root to the path so we can import safeparse.
project_root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, project_root)

from safeparse.compiler import compile_spec


# Each entry is (spec_file_relative_path, output_base_name).
SPECS = [
    ("specs/udp.spec",      "udp"),
    ("specs/png_ihdr.spec", "png_ihdr"),
    ("specs/dns.spec",      "dns"),
]


def read_file(file_path):
    """
    Read and return the full contents of a text file.

    WHAT: Opens a file and reads it as a string.
    WHY:  We need the spec text to pass to compile_spec().
    """
    handle = open(file_path, "r")
    text = handle.read()
    handle.close()
    return text


def write_file(file_path, content):
    """
    Write a string to a file, creating parent directories if needed.

    WHAT: Writes content to the given path.
    WHY:  We need to save the generated C code to disk.
    """
    directory = os.path.dirname(file_path)
    if not os.path.exists(directory):
        os.makedirs(directory)

    handle = open(file_path, "w")
    handle.write(content)
    handle.close()


def generate_all():
    """
    Generate naive and optimized C headers for every spec.

    WHAT: Loops over all specs, calls compile_spec() twice (once per mode),
          and writes 6 .h files into c_tests/generated/.
    WHY:  The C test harnesses need these files at compile time.
    """
    output_dir = os.path.join(project_root, "c_tests", "generated")

    for spec_path, base_name in SPECS:
        full_path = os.path.join(project_root, spec_path)
        spec_text = read_file(full_path)

        for mode in ["naive", "optimized"]:
            result = compile_spec(spec_text, mode)

            if not result["success"]:
                print("ERROR compiling {} in {} mode:".format(spec_path, mode))
                for error in result["errors"]:
                    print("  " + error)
                sys.exit(1)

            # Build a header-safe version: wrap in an include guard.
            guard_name = "SAFEPARSE_{}_{}".format(base_name.upper(), mode.upper())
            header_lines = []
            header_lines.append("/* AUTO-GENERATED by generate_headers.py */")
            header_lines.append("/* Spec: {}  Mode: {} */".format(spec_path, mode))
            header_lines.append("")
            header_lines.append("#ifndef {}".format(guard_name))
            header_lines.append("#define {}".format(guard_name))
            header_lines.append("")

            # The generated code already has #includes and #defines.
            # We need to rename the return-code defines and struct/function
            # names so naive and optimized versions can coexist in one
            # compilation unit.
            c_code = result["c_code"]
            format_name = result["format_name"]

            # For the naive version, prefix everything with naive_.
            # For optimized, prefix with opt_.
            if mode == "naive":
                prefix = "naive"
            else:
                prefix = "opt"

            # Replace function name: parse_X -> naive_parse_X / opt_parse_X
            c_code = c_code.replace(
                "parse_{}".format(format_name),
                "{}_parse_{}".format(prefix, format_name),
            )
            # Replace struct name: } X; -> } naive_X; / } opt_X;  etc.
            c_code = c_code.replace(
                "}} {};".format(format_name),
                "}} {}_{};".format(prefix, format_name),
            )
            c_code = c_code.replace(
                "{} *out".format(format_name),
                "{}_{} *out".format(prefix, format_name),
            )
            c_code = c_code.replace(
                "of {}".format(format_name),
                "of {}_{}".format(prefix, format_name),
            )
            # Replace the #define names to avoid redefinition between headers.
            c_code = c_code.replace(
                "#define PARSE_OK",
                "#define {}_PARSE_OK".format(prefix.upper()),
            )
            c_code = c_code.replace(
                "#define PARSE_ERR_TOO_SHORT",
                "#define {}_PARSE_ERR_TOO_SHORT".format(prefix.upper()),
            )
            c_code = c_code.replace(
                "#define PARSE_ERR_BAD_LENGTH",
                "#define {}_PARSE_ERR_BAD_LENGTH".format(prefix.upper()),
            )
            # Replace return code usage to match renamed defines.
            c_code = c_code.replace(
                "return PARSE_OK;",
                "return {}_PARSE_OK;".format(prefix.upper()),
            )
            c_code = c_code.replace(
                "return PARSE_ERR_TOO_SHORT;",
                "return {}_PARSE_ERR_TOO_SHORT;".format(prefix.upper()),
            )
            c_code = c_code.replace(
                "return PARSE_ERR_BAD_LENGTH;",
                "return {}_PARSE_ERR_BAD_LENGTH;".format(prefix.upper()),
            )

            header_lines.append(c_code)
            header_lines.append("#endif /* {} */".format(guard_name))
            header_lines.append("")

            output_file = os.path.join(
                output_dir, "{}_{}.h".format(base_name, mode)
            )
            write_file(output_file, "\n".join(header_lines))
            print("Generated: {}".format(output_file))

    print("")
    print("All headers generated successfully.")


# Run the generator when this script is executed directly.
if __name__ == "__main__":
    generate_all()
